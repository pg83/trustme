fn main() {
    for left in 0..16u8 {
        for right in 0..16u8 {
            for first in [false, true] {
                assert_eq!(choose(first, left, right), if first { left as u32 * 100 + 7 } else { right as u32 * 100 + 11 });
            }
        }
    }
    assert_eq!(choose(true, 16, 0), 9999);
    assert_eq!(choose(false, 0, 16), 9999);
}

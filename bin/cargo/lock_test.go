package main

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

func TestParseLockReadsVersionOneMetadataChecksums(t *testing.T) {
	path := filepath.Join(t.TempDir(), "Cargo.lock")

	lock := `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
[[package]]
name = "assert_matches"
version = "1.5.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "futures"
version = "0.3.34"
dependencies = [
 "assert_matches 1.5.0 (registry+https://github.com/rust-lang/crates.io-index)",
]

[metadata]
"checksum assert_matches 1.5.0 (registry+https://github.com/rust-lang/crates.io-index)" = "9b34d609dfbaf33d6889b2b7106d3ca345eacad44200913df5ba02bfd31d2ba9"
`

	if err := os.WriteFile(path, []byte(lock), 0o644); err != nil {
		t.Fatal(err)
	}

	want := []Pkg{
		{
			name:     "assert_matches",
			version:  "1.5.0",
			source:   "registry+https://github.com/rust-lang/crates.io-index",
			checksum: "9b34d609dfbaf33d6889b2b7106d3ca345eacad44200913df5ba02bfd31d2ba9",
		},
		{name: "futures", version: "0.3.34"},
	}

	if got := parseLock(path); !reflect.DeepEqual(got, want) {
		t.Fatalf("parseLock() = %#v, want %#v", got, want)
	}
}
